/* Pasang daftar ke <input list=...>. altEl (opsional) terisi otomatis bila nama cocok dan belum diisi manual. Mengembalikan fungsi pencari. */
window.IB_MountainBind=function(input,altEl){
  var id="mtnList",dl=document.getElementById(id);
  if(!dl){dl=document.createElement("datalist");dl.id=id;
    dl.innerHTML=IB_MOUNTAINS.map(function(m){var o=document.createElement("option");o.value=m[0];o.label=m[1]+(m[2]?" · "+m[2]+" mdpl":"");return o.outerHTML}).join("");
    document.body.appendChild(dl)}
  input.setAttribute("list",id);input.setAttribute("autocomplete","off");
  function find(v){v=String(v||"").trim().toLowerCase();for(var i=0;i<IB_MOUNTAINS.length;i++)if(IB_MOUNTAINS[i][0].toLowerCase()===v)return IB_MOUNTAINS[i];return null}
  input.addEventListener("change",function(){var m=find(input.value);if(m){input.value=m[0];if(altEl&&m[2]&&!altEl.value){altEl.value=m[2];altEl.dispatchEvent(new Event("input",{bubbles:true}))}}});
  return find};
